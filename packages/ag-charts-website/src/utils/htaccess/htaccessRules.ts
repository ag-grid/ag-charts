import type { AstroUserConfig } from 'astro';

import { SITE_BASE_URL } from '../../constants';
import { markdownPathAlternation } from '../markdownPages';
import { urlWithBaseUrl } from '../urlWithBaseUrl';
import type { CspEnv } from './cspRules';
import { getCspHtaccessBlock, getScopedCspHtaccessBlock } from './cspRules';
import { SITE_301_REDIRECTS, type SimpleRedirectRule } from './redirects';

export type HtaccessEnv = Extract<CspEnv, 'staging' | 'production'>;

// Rollout state for removing 'unsafe-eval' from the production main-site CSP. Staging always
// enforces the split; flip this to 'enforce' once production's report-only window is clean.
export const PRODUCTION_CSP_PHASE: 'report-only' | 'enforce' = 'enforce';

export function getHtaccessContent(options: { env: HtaccessEnv }) {
    const { env } = options;
    return `### AUTOGENERATED DO NOT EDIT
ErrorDocument 404 ${urlWithBaseUrl('/404.html')}

# add MIME types for serving example files
AddType text/javascript mjs ts jsx

# serve the per-page LLM markdown files as markdown
AddType text/markdown md
# ...as UTF-8, so glyphs like ✓/✗ in generated tables aren't mojibaked by a
# Latin-1 fallback (the .md endpoint sets this charset; static hosting must too).
AddCharset utf-8 .md

# Content-Security-Policy — path-scoped. Charts is served from /charts on www.ag-grid.com
# and inherits the grid root CSP, so this block overrides it for charts pages (see
# getCspHtaccessBlock). Ordinary pages get the tightened policy (no 'unsafe-eval'); the
# <If> override re-allows it for example-runner documents. The trial-form origin is
# env-split, so the policy is generated per environment.
${getCspContent(env)}

${getMarkdownNegotiationRules()}

${getRedirectRules()}

Options -Indexes
`;
}

function getCspContent(env: HtaccessEnv): string {
    // The Report-Only <If> override is load-bearing: without it every example-runner page
    // would report eval violations.
    if (env === 'staging' || PRODUCTION_CSP_PHASE === 'enforce') {
        return getScopedCspHtaccessBlock({ env }, 'enforce');
    }
    return `${getCspHtaccessBlock({ env, scope: 'examples' }, 'enforce')}

${getScopedCspHtaccessBlock({ env }, 'report-only')}`;
}

export function getRedirectRules() {
    // Unlike mod_rewrite, mod_alias does not strip the directory prefix, so patterns must carry
    // the base; rule definitions stay base-relative and it is spliced in here.
    const basePath = (SITE_BASE_URL ?? '').replace(/\/$/, '');
    const toBaseAwarePattern = (fromPattern: string) =>
        fromPattern.startsWith('^') ? `^${basePath}${fromPattern.slice(1)}` : `${basePath}${fromPattern}`;
    return `${SITE_301_REDIRECTS.map((redirect) => {
        const { from, fromPattern, to, gone } = redirect as any;
        if (!from && !fromPattern) {
            // eslint-disable-next-line no-console
            console.warn('Missing `from` in redirect', redirect);
            return;
        }
        // 410 Gone: permanently removed, no target.
        if (gone) {
            return from
                ? `Redirect 410 ${urlWithBaseUrl(from)}`
                : `RedirectMatch 410 "${toBaseAwarePattern(fromPattern)}"`;
        }
        if (!to) {
            // eslint-disable-next-line no-console
            console.warn('Missing `to` in redirect', redirect);
            return;
        }
        if (from) {
            return `Redirect 301 ${urlWithBaseUrl(from)} ${urlWithBaseUrl(to)}`;
        }
        return `RedirectMatch 301 "${toBaseAwarePattern(fromPattern)}" "${urlWithBaseUrl(to)}"`;
    })
        .filter(Boolean)
        .join('\n')}`;
}

export function getMarkdownNegotiationRules() {
    // %1 must be document-root-relative for both the on-disk `-f` test and the rewrite target to
    // resolve, so the base is captured inside it rather than matched outside.
    const basePath = (SITE_BASE_URL ?? '').replace(/\/$/, '');
    const baseRelative = basePath.replace(/^\//, '');
    const capturePrefix = baseRelative ? `${baseRelative}/` : '';
    const pages = markdownPathAlternation();
    const negotiatedPath = `^/(${capturePrefix}(?:${pages}))/?$`;
    // Must match negotiatedPath's shape exactly, or Vary: Accept lands on non-negotiating URLs
    // and fragments shared caches.
    const varyScope = `^${basePath}/(?:${pages})/?$`;

    // Serve the per-page markdown twin on Accept: text/markdown. An internal rewrite gated by an
    // on-disk check, so a path with no twin is left untouched.
    return `<IfModule mod_rewrite.c>
    RewriteEngine On

    RewriteCond %{HTTP_ACCEPT} text/markdown
    RewriteCond %{REQUEST_URI} ${negotiatedPath}
    RewriteCond %{DOCUMENT_ROOT}/%1.md -f
    RewriteRule ^ /%1.md [L]

    # The homepage twin (${basePath}/ -> ${basePath}/index.md). Handled separately because the
    # site root has no path segment to capture in %1; the pattern matches only the base root.
    RewriteCond %{HTTP_ACCEPT} text/markdown
    RewriteCond %{REQUEST_URI} ^${basePath}/?$
    RewriteCond %{DOCUMENT_ROOT}${basePath}/index.md -f
    RewriteRule ^ ${basePath}/index.md [L]
</IfModule>

# Docs pages content-negotiate on Accept (see the markdown rewrite), so shared caches must
# key on it. Scoped to the negotiated paths (incl. the homepage) so the rest of the site keeps
# its default.
<If "%{REQUEST_URI} =~ m#${varyScope}# || %{REQUEST_URI} =~ m#^${basePath}/?$#">
    Header append Vary Accept
</If>`;
}

export function getAstroRedirectRules(): AstroUserConfig['redirects'] {
    // Gone rules have no `to`, so skip them.
    const simpleRedirects = SITE_301_REDIRECTS.filter(
        (redirect) => Boolean((redirect as SimpleRedirectRule).from) && !(redirect as { gone?: true }).gone
    ) as SimpleRedirectRule[];

    return Object.fromEntries(
        simpleRedirects.map(({ from, to }) => {
            // Astro adds the base to the `from` side.
            return [from, urlWithBaseUrl(to)];
        })
    );
}
