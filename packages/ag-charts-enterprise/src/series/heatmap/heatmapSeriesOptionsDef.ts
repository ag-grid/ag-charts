import type {
    AgHeatmapSeriesLabelStyle,
    AgHeatmapSeriesOptions,
    AgHeatmapSeriesStyle,
    AgHeatmapSeriesThemeableOptions,
} from 'ag-charts-community';
import {
    type OptionsDefs,
    autoSizedLabelOptionsDefs,
    boolean,
    callbackDefs,
    colorScaleOptionsDef,
    commonSeriesOptionsDefs,
    commonSeriesThemeableOptionsDefs,
    constant,
    fillOptionsDef,
    fontOptionsDef,
    glowHighlightOptionsDef,
    glowOptionsDefs,
    labelBoxOptionsDef,
    positiveNumber,
    required,
    shadowOptionsDefs,
    shapeHighlightOptionsDef,
    string,
    strokeOptionsDef,
    textAlign,
    tooltipOptionsDefs,
    union,
    without,
} from 'ag-charts-core';

export const heatmapSeriesThemeableOptionsDef: OptionsDefs<AgHeatmapSeriesThemeableOptions> = {
    title: string,
    itemPadding: positiveNumber,
    cornerRadius: positiveNumber,
    shadow: shadowOptionsDefs,
    glow: glowOptionsDefs,
    itemStyler: callbackDefs<AgHeatmapSeriesStyle>(
        {
            ...fillOptionsDef,
            ...strokeOptionsDef,
        },
        undefined,
        { rememberResults: true }
    ),
    showInMiniChart: boolean,
    label: {
        ...autoSizedLabelOptionsDefs,
        textAlign,
        verticalAlign: union('top', 'middle', 'bottom'),
        itemStyler: callbackDefs<AgHeatmapSeriesLabelStyle>({
            enabled: boolean,
            ...labelBoxOptionsDef,
            ...fontOptionsDef,
            textAlign,
            verticalAlign: union('top', 'middle', 'bottom'),
        }),
    },
    tooltip: tooltipOptionsDefs,
    colorScale: colorScaleOptionsDef,
    ...commonSeriesThemeableOptionsDefs,
    highlight: glowHighlightOptionsDef(shapeHighlightOptionsDef),
    ...strokeOptionsDef,
};

export const heatmapSeriesOptionsDef: OptionsDefs<AgHeatmapSeriesOptions> = {
    ...without(heatmapSeriesThemeableOptionsDef, ['showInLegend']),
    ...without(commonSeriesOptionsDefs, ['showInLegend', 'highlight']),
    type: required(constant('heatmap')),
    xKey: required(string),
    yKey: required(string),
    xKeyAxis: string,
    yKeyAxis: string,
    colorKey: string,
    xName: string,
    yName: string,
    colorName: string,
    colorScale: colorScaleOptionsDef,
};
